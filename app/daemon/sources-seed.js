// Tunisia is the target market, so its boards are polled on a tighter clock than
// the per-source values above give them: keejob/tunisiejob/tanisjobs were 45 min
// and sagemcom 10 min, which on its own was most of the notification latency --
// an offer posted on a Tunisia-only board sat unpolled long before any digest ran.
// Capped, never lowered. Mirrors TN_INTERVAL_CAP in seed-registry.js, which does
// the same for the registry (ATS) boards; both seeders are needed because a source
// is owned by whichever one created it.
const TN_INTERVAL_CAP = 300000;
for (const src of Object.values(SOURCES)) {
  if (/^(tn|tunisie|tunisia)$/i.test(String(src.country || '').trim())
      && Number(src.intervalMs || 0) > TN_INTERVAL_CAP) {
    src.intervalMs = TN_INTERVAL_CAP;
  }
}


async function main() {
  for (const [id, src] of Object.entries(SOURCES)) {
    try {
      await api.createSource({ id, ...src });
      console.log('seeded:', id);
    } catch (e) {
      console.error('seed failed', id, ':', String((e && e.message) || e).slice(0,120));
    }
  }
  console.log('DONE');
}

if (require.main === module) main().then(() => process.exit(0)).catch((e) => { console.error(e); process.exit(1); });
module.exports = { SOURCES };
